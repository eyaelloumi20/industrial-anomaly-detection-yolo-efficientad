"""
retrain_efficientad.py
======================
Retrains EfficientAD (Student + AutoEncoder) on the YOLO-cropped dataset
produced by crop_dataset_video1.py / crop_dataset.py.

The teacher (best_teacher.pth) is kept frozen — only Student and AutoEncoder
are trained, exactly as in the original EfficientAD paper (Algorithm 1).

Key details
-----------
  - Dataset: cropped 256×256 images
  - channel_mean/std: recomputed from the cropped training images
  - quantiles: recomputed on the TEST split (normal-only held-out set)
  - AUROC monitored on the VALIDATION split (normal + anomaly)
  - All get_AD_dataset calls pass split_ratio=1.0 so the CSV-defined
    splits are used verbatim (no internal re-shuffling)

THREE-SPLIT convention (generated by generate_csv.py):
  train      – normal images only          → student / AE training
  test       – normal images only (small)  → quantile calibration
  validation – normal + anomaly            → AUROC monitoring & best-ckpt

Fixes vs previous version
-------------------------
  * split_ratio=1.0 on all three get_AD_dataset calls
  * hard feature loss uses dist.flatten() (not dist[:8])
  * validation-phase fallback: if the data_loader doesn't recognize
    'validation', try 'val' then fall back to 'test'
  * print_freq default raised to 1000 to cut evaluation overhead ~5×

Usage
-----
 python retrain_efficientad.py \
   --dataset_path /home/ahmed/two-stage-efficientad-inspection/dataset_root \
   --ckpt_dir /home/ahmed/two-stage-efficientad-inspection/ckpt_cropped_retrain \
   --teacher_path /home/ahmed/framework/ckpt_cropped_large1/best_teacher.pth \
   --category chewinggum \
   --model_size S \
   --iterations 70000 \
   --batch_size 1 \
   --lr 1e-4 \
   --print_freq 1000 \
   --device cuda:0 \
   --no_imagenet
"""

