#!/usr/bin/env bash
set -Eeuo pipefail

ROOT="/home/ahmed/two-stage-efficientad-inspection"
cd "$ROOT"

DETECTOR="video_streaming_detector_simple_optimized_v2.py"
VIDEO="./video_test/video_A.mp4"
YOLO="./runs/detect/yolo_runs/chewinggum_yolov8n_v2/weights/best.pt"

run_variant () {
    local NAME="$1"
    local METHOD="$2"
    local CKPT="$3"
    local THR="$4"

    echo "======================================================================"
    echo "CALIBRATED VIDEO: $NAME"
    echo "======================================================================"

    python "$DETECTOR" \
      --video "$VIDEO" \
      --yolo_det_weights "$YOLO" \
      --method "$METHOD" \
      --ckpt_dir "$CKPT" \
      --thresholds_json "$THR" \
      --category chewinggum \
      --model_size S \
      --device cuda:0 \
      --fp16 \
      --threshold_basis ema \
      --ema_alpha 0.3 \
      --clip_margin 5 \
      --min_box_frac 0.5 \
      --batch_frames 16 \
      --batch_crops 96 \
      --gpu_batch_crops 8 \
      --crop_workers 12 \
      --no_detect_unknown \
      --save_dir "./calibrated_results/$NAME/video_A"
}

# Baseline: existing calibrated threshold
run_variant \
  "baseline" \
  "baseline" \
  "./ckpt_cropped_multi" \
  "./video_calibration_new/video_thresholds_baseline_v2.json"

# Optimized variants: generated by calibrate_ema_thresholds.py
run_variant \
  "lowres192" \
  "lowres" \
  "./ckpt_lowres_192" \
  "./video_calibration_new/video_thresholds_lowres192_ema.json"

run_variant \
  "lowres224" \
  "lowres" \
  "./ckpt_lowres_224" \
  "./video_calibration_new/video_thresholds_lowres224_ema.json"

run_variant \
  "thin075" \
  "thin" \
  "./ckpt_thin_075" \
  "./video_calibration_new/video_thresholds_thin075_ema.json"

run_variant \
  "thin050" \
  "thin" \
  "./ckpt_thin_050" \
  "./video_calibration_new/video_thresholds_thin050_ema.json"

run_variant \
  "pruned030" \
  "pruned" \
  "./ckpt_pruned_030" \
  "./video_calibration_new/video_thresholds_pruned030_ema.json"

echo
echo "All calibrated videos are under:"
echo "  $ROOT/calibrated_results/"
